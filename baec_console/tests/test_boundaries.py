"""Static product boundaries: offline, no model, no outreach path, no research infrastructure."""

from __future__ import annotations

import ast
import re
from pathlib import Path

CONSOLE = Path(__file__).resolve().parents[1]
SOURCES = sorted(p for p in CONSOLE.glob("*.py"))


def _imports(path: Path) -> set[str]:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    found = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            found |= {a.name for a in node.names}
        elif isinstance(node, ast.ImportFrom) and node.module:
            found.add(node.module)
    return found


def test_no_network_model_or_messaging_library_is_imported():
    banned = ("anthropic", "openai", "httpx", "requests", "urllib", "http", "socket", "smtplib", "email", "imaplib",
              "mcp", "baec_app.ai", "baec_app.mcp", "baec_app.mcp_write")
    for path in SOURCES:
        for name in _imports(path):
            assert not any(name == b or name.startswith(b + ".") for b in banned), (path.name, name)


def test_no_research_infrastructure_is_used():
    banned = ("stage_f", "autonomous", "calibration", "experiments", "offline_evaluation import evaluate",
              "live_claude")
    for path in SOURCES:
        text = path.read_text(encoding="utf-8").lower()
        for word in banned:
            assert word not in text, (path.name, word)


def test_no_send_or_crm_action_exists():
    for path in SOURCES:
        tree = ast.parse(path.read_text(encoding="utf-8"))
        names = {n.name.lower() for n in ast.walk(tree) if isinstance(n, (ast.FunctionDef, ast.ClassDef))}
        for name in names:
            for word in ("send", "outreach", "crm", "mailbox", "schedule", "notify", "dispatch"):
                assert word not in name, (path.name, name)
    for path in SOURCES:
        text = path.read_text(encoding="utf-8")
        for label in ("Send", "Ready to send", "Approved for outreach", "Send now", "mailto:"):
            assert f'"{label}' not in text and f"'{label}" not in text, (path.name, label)


def test_no_secrets_or_keys_in_console_sources():
    for path in CONSOLE.rglob("*"):
        if (path.is_file() and path.suffix in (".py", ".md", ".toml", ".txt") and ".data" not in path.parts
                and path != Path(__file__).resolve()):
            text = path.read_text(encoding="utf-8")
            assert "sk-ant" not in text and "API_KEY" not in text.upper().replace(" ", "_"), path.name


def test_template_output_is_never_labelled_ai():
    for path in SOURCES:
        text = path.read_text(encoding="utf-8")
        for label in ("AI-generated", "AI generated", "Generated by AI", "AI draft"):
            # A denial ("not AI-generated") is the required disclosure; a label is not allowed.
            assert not re.search(rf"(?<!not ){label}", text), (path.name, label)


def test_streamlit_makes_no_network_request_and_listens_locally():
    config = (CONSOLE / ".streamlit" / "config.toml").read_text(encoding="utf-8")
    assert "gatherUsageStats = false" in config  # usage statistics would be sent over the network
    # Without a specific address, a headless Streamlit start looks up the public IP for its "External URL" banner.
    assert 'address = "localhost"' in config and 'serverAddress = "localhost"' in config


def test_local_data_is_ignored_by_git():
    assert ".data/" in (CONSOLE / ".gitignore").read_text(encoding="utf-8").split()
